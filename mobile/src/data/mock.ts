/** Génère des photos fictives pour une espèce. */
function makePhotos(speciesSlug: string, count: number, lastSeenAt: string): Photo[] {
  const last = new Date(lastSeenAt).getTime();
  return Array.from({ length: count }, (_, i) => {
    const seed = `${speciesSlug}-${i}`;
    return {
      id: seed,
      speciesSlug,
      imageUrl: `https://picsum.photos/seed/${seed}/1200/900`,
      thumbnailUrl: `https://picsum.photos/seed/${seed}/300/300`,
      // une photo toutes les ~9 h en remontant dans le temps
      takenAt: new Date(last - i * 9 * 60 * 60 * 1000).toISOString(),
      sensorId: 'capteur-jardin-01',
    };
  });
}

export const mockPhotos: Photo[] = mockSpecies.flatMap((s) =>
  s.lastSeenAt ? makePhotos(s.slug, s.photoCount, s.lastSeenAt) : [],
);
